# 2. CORRECTED & ROBUST PRODUCTION VERSION (AFTER TESTING & DEBUGGING)
# =============================================================================
def corrected_production_code(db_name="food_delivery_orders.db", output_image="ai_top3_restaurants.png"):
    """
    Production-grade, fully debugged implementation:
    - Pre-flight database existence verification using os.path.isfile()
    - SQLite URI read-only connection or strict existence check to prevent 0-byte DB creation
    - Robust SQL query with properly structured GROUP BY, HAVING, and ORDER BY clauses
    - Graceful empty dataset check before performing analytical operations
    - Safe zero-division protection when computing revenue share percentage
    - Highly readable horizontal bar chart with formatted data labels and complete axis titles
    - Clean resource management with context managers (with sqlite3.connect)
    """
    # 1. File existence validation
    if not os.path.isfile(db_name):
        print(f"\n[ERROR] Database file '{db_name}' not found. Please verify the file path.")
        return None

    try:
        # Use context manager to guarantee connection closing
        with sqlite3.connect(f"file:{db_name}?mode=ro", uri=True) as conn:
            query = """
            SELECT 
                restaurant_name,
                ROUND(AVG(rating), 2) AS avg_rating,
                COUNT(order_id) AS total_orders,
                ROUND(SUM(order_value), 2) AS total_revenue
            FROM orders
            GROUP BY restaurant_name
            HAVING COUNT(order_id) >= 5
            ORDER BY avg_rating DESC
            LIMIT 3;
            """
            df = pd.read_sql_query(query, conn)

    except sqlite3.OperationalError as db_err:
        print(f"\n[DATABASE ERROR] Failed executing SQL query on '{db_name}': {db_err}")
        return None
    except Exception as exc:
        print(f"\n[UNEXPECTED ERROR] An error occurred while retrieving data: {exc}")
        return None

    # 2. Check for empty DataFrame
    if df is None or df.empty:
        print("\n[USER NOTICE] No restaurants found matching the criteria (Minimum 5 orders required).")
        return None

    # 3. Revenue Share Calculation with zero-division safeguard
    total_combined_revenue = df['total_revenue'].sum()
    if total_combined_revenue > 0:
        df['revenue_share_pct'] = (df['total_revenue'] / total_combined_revenue) * 100.0
    else:
        df['revenue_share_pct'] = 0.0

    print("\n--- [TOP 3 RESTAURANTS BY AVERAGE RATING (MIN 5 ORDERS)] ---")
    display_df = df[['restaurant_name', 'avg_rating', 'total_orders', 'total_revenue', 'revenue_share_pct']].copy()
    display_df['revenue_share_pct'] = display_df['revenue_share_pct'].map("{:.1f}%".format)
    display_df['total_revenue'] = display_df['total_revenue'].map("INR {:,.2f}".format)
    print(display_df.to_string(index=False))

    # 4. Invert order so highest rating appears at the top of the horizontal bar chart
    plot_df = df.iloc[::-1].reset_index(drop=True)

    # 5. Visualisation with Matplotlib
    plt.figure(figsize=(10, 5))
    bar_positions = np.arange(len(plot_df))
    bars = plt.barh(bar_positions, plot_df['avg_rating'], color='#2b5c8f', edgecolor='#1a365d', height=0.55)

    plt.yticks(bar_positions, plot_df['restaurant_name'], fontsize=11, fontweight='semibold')
    plt.xlim(0, 5.5)
    plt.xlabel("Average Customer Rating (Scale: 1.0 - 5.0)", fontsize=11, fontweight='bold', labelpad=10)
    plt.ylabel("Restaurant Partner", fontsize=11, fontweight='bold', labelpad=10)
    plt.title("Top 3 Rated Restaurants (Min. 5 Orders) with Revenue Share %", fontsize=13, fontweight='bold', pad=15)
    plt.grid(axis='x', linestyle='--', alpha=0.5)

    # Annotate bars with revenue share percentage and rating score
    for bar, (_, row) in zip(bars, plot_df.iterrows()):
        x_val = bar.get_width()
        y_val = bar.get_y() + bar.get_height() / 2
        label_text = f" Rating: {row['avg_rating']:.2f}  |  Rev Share: {row['revenue_share_pct']:.1f}%"
        plt.annotate(
            label_text,
            xy=(x_val, y_val),
            xytext=(6, 0),
            textcoords="offset points",
            va='center',
            ha='left',
            fontsize=10,
            fontweight='bold',
            color='#1a365d'
        )

    plt.tight_layout()
    plt.savefig(output_image, dpi=150, bbox_inches='tight')
    plt.close()
    print(f"\n[CHART SAVED] Top 3 restaurants horizontal bar chart saved to: '{os.path.abspath(output_image)}'")
    return df

